-- Schema only: no personal data, credentials or database dumps.
CREATE DATABASE IF NOT EXISTS bi CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE bi;

CREATE TABLE IF NOT EXISTS user (
  id BIGINT PRIMARY KEY,
  userAccount VARCHAR(256) NOT NULL,
  userPassword VARCHAR(512) NOT NULL,
  userName VARCHAR(256),
  userAvatar VARCHAR(1024),
  userRole VARCHAR(256) NOT NULL DEFAULT 'user',
  createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  isDelete TINYINT NOT NULL DEFAULT 0,
  UNIQUE KEY uk_user_account (userAccount)
);

CREATE TABLE IF NOT EXISTS chart (
  id BIGINT PRIMARY KEY,
  goal TEXT,
  name VARCHAR(256),
  chartData MEDIUMTEXT,
  chartType VARCHAR(128),
  genChart MEDIUMTEXT,
  genResult MEDIUMTEXT,
  status VARCHAR(128) DEFAULT 'wait',
  execMessage TEXT,
  userId BIGINT NOT NULL,
  createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  isDelete TINYINT NOT NULL DEFAULT 0,
  KEY idx_chart_user (userId)
);

CREATE TABLE IF NOT EXISTS post (
  id BIGINT PRIMARY KEY,
  title VARCHAR(512),
  content TEXT,
  tags VARCHAR(1024),
  thumbNum INT NOT NULL DEFAULT 0,
  favourNum INT NOT NULL DEFAULT 0,
  userId BIGINT NOT NULL,
  createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  isDelete TINYINT NOT NULL DEFAULT 0,
  KEY idx_post_user (userId)
);

CREATE TABLE IF NOT EXISTS post_thumb (
  id BIGINT PRIMARY KEY,
  postId BIGINT NOT NULL,
  userId BIGINT NOT NULL,
  createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_thumb_post (postId),
  KEY idx_thumb_user (userId)
);

CREATE TABLE IF NOT EXISTS post_favour (
  id BIGINT PRIMARY KEY,
  postId BIGINT NOT NULL,
  userId BIGINT NOT NULL,
  createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_favour_post (postId),
  KEY idx_favour_user (userId)
);
